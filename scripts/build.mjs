import { build } from 'esbuild';
import { mkdir, readFile, writeFile, readdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
await mkdir(output, { recursive: true });
await build({ entryPoints: [path.join(root, 'web/app.js')], bundle: true, format: 'esm', target: 'chrome120', outfile: path.join(output, 'app.js'), minify: true, legalComments: 'eof' });
const assets = {};
async function addAsset(url, filename, type) {
  assets[url] = { type, base64: (await readFile(filename)).toString('base64') };
}
await copyFile(path.join(root, 'web/index.html'), path.join(output, 'index.html'));
await copyFile(path.join(root, 'web/styles.css'), path.join(output, 'styles.css'));
await addAsset('/index.html', path.join(output, 'index.html'), 'text/html; charset=utf-8');
await addAsset('/styles.css', path.join(output, 'styles.css'), 'text/css; charset=utf-8');
await addAsset('/app.js', path.join(output, 'app.js'), 'text/javascript; charset=utf-8');
await addAsset('/third-party-licenses.txt', path.join(root, 'licenses/THIRD_PARTY_LICENSES.txt'), 'text/plain; charset=utf-8');
await addAsset('/pdf.worker.min.mjs', path.join(root, 'node_modules/pdfjs-dist/build/pdf.worker.min.mjs'), 'text/javascript; charset=utf-8');
for (const folder of ['cmaps', 'standard_fonts', 'wasm']) {
  const directory = path.join(root, 'node_modules/pdfjs-dist', folder);
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isFile() && !/LICENSE|\.js$|\.md$/i.test(entry.name)) {
      await addAsset(`/${folder}/${entry.name}`, path.join(directory, entry.name), entry.name.endsWith('.wasm') ? 'application/wasm' : 'application/octet-stream');
    }
  }
}
await mkdir(path.join(root, 'server'), { recursive: true });
await writeFile(path.join(root, 'server/assets.generated.ts'), '// Generated by npm run build. Do not edit.\nexport const assets: Record<string, {type: string; base64: string}> = ' + JSON.stringify(assets) + ';\n');
console.log(`Built ${Object.keys(assets).length} local viewer assets.`);
